#!/usr/bin/env python3
"""
gen_manifest2.py -- THEMISTOCLES-II Roblox manifest generator.

Reads boats/exports/<dir>/<class>_export_meta.json and emits a Lua manifest
module for roblox/src/Manifest_<class>.lua.  Moving parts keep their object
origin at the animation pivot (rowlock / pintle / shaft hub) so BuildBoat can
just insert them and the controllers rotate them about their own origin.

Usage: gen_manifest2.py boats/exports/rowing2/rowing_cutter_25ft_export_meta.json
"""
import json, os, sys

STUD = 0.28  # metres per stud


def emit(meta, boat_id):
    s = []
    s.append("--!nonstrict")
    s.append(f"-- AUTO-GENERATED by roblox/tools/gen_manifest2.py (THEMISTOCLES-II) from")
    s.append(f"-- boats/exports meta for {boat_id} -- do not edit by hand.")
    s.append("-- Positions are in STUDS, in the model frame: +X bow, +Z up, +Y port.")
    s.append("-- Z=0 is the LOADED waterline (this generation); origin at mid-LOA.")
    s.append("")
    s.append("return {")
    s.append(f"\tboat_id = \"{boat_id}\",")
    s.append(f"\tstud_per_m = {1/STUD:g},")
    parts = meta["parts"]
    # moving-part pivots
    pivs = meta["pivots"]
    moving = {}
    for o in pivs.get("oars_moving", []):
        moving[o["part"]] = o["pivot_world"]
    if "rudder_axis" in pivs:
        moving["Rudder"] = pivs["rudder_axis"]
    if "propeller" in pivs:
        moving["Propeller"] = pivs["propeller"]["hub_pt"]
    s.append("\tmoving_pivots = {")
    for nm, pw in sorted(moving.items()):
        x, y, z = (pw[0] / STUD, pw[1] / STUD, pw[2] / STUD)
        s.append(f"\t\t[\"{nm}\"] = Vector3.new({x:.4f}, {y:.4f}, {z:.4f}),")
    s.append("\t},")
    s.append("\tparts = {")
    # roles by name
    def role(nm):
        n = nm.lower()
        if nm in moving: return "moving"
        if any(w in n for w in ("planking", "transom", "keel", "stems", "stern_post",
                                "gunwale", "keelson", "breasthook", "stem_post")):
            return "hull" if "planking" in n or "transom" in n else "structure"
        if any(w in n for w in ("frame", "bench", "thwart", "grating", "stretcher",
                                "riser", "knee", "sheet", "case", "gusset")):
            return "furniture" if "frame" not in n else "structure"
        if any(w in n for w in ("oar_", "rig_", "mast")): return "rig"
        if any(w in n for w in ("boiler", "engine", "funnel", "shaft", "pipe",
                                "bunker", "tank", "pump", "mountings", "bearers",
                                "helm", "steering", "brace", "chains", "bracket",
                                "fire", "flooring", "cabin", "sidelight")):
            return "machinery"
        return "gear"
    for nm in sorted(parts):
        p = parts[nm]
        d = p["dimensions_m"]
        org = p["origin_m"]
        s.append(f"\t\t{{ name = \"{nm}\", role = \"{role(nm)}\", "
                 f"origin = Vector3.new({org[0]/STUD:.4f}, {org[1]/STUD:.4f}, {org[2]/STUD:.4f}), "
                 f"size = Vector3.new({d[0]/STUD:.4f}, {d[1]/STUD:.4f}, {d[2]/STUD:.4f}), "
                 f"verts = {p.get('vertices', 0)}, tris = {p.get('triangles', 0)} }},")
    s.append("\t},")
    hy = meta["hydrostatics"]
    s.append(f"\thydro = {{ loaded_draft_studs = {hy['loaded']['draft_m']/STUD:.3f}, "
             f"light_draft_studs = {hy['light']['draft_m']/STUD:.3f}, "
             f"displacement_kg = {{ {hy['loaded']['displacement_kg']}, {hy['light']['displacement_kg']} }} }},")
    s.append("}")
    return "\n".join(s)


if __name__ == "__main__":
    path = sys.argv[1]
    meta = json.load(open(path))
    boat_id = meta["class"]
    out = os.path.join(os.path.dirname(path), "..", "..", "..", "roblox", "src",
                       f"Manifest_{boat_id}.lua")
    out = os.path.normpath(out)
    with open(out, "w") as f:
        f.write(emit(meta, boat_id) + "\n")
    print("WROTE", out)
